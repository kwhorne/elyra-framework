/// specta-typescript renders these as a bare `number`; every other numeric is
/// coerced to `i32` so it renders the same way (rather than `bigint` for 64-bit
/// ints, or `number | null` for floats).
fn coerced_primitive(p: &Primitive) -> Option<Primitive> {
    let renders_as_plain_number = matches!(
        p,
        Primitive::i8
            | Primitive::i16
            | Primitive::i32
            | Primitive::u8
            | Primitive::u16
            | Primitive::u32
    );
    let is_numeric = matches!(
        p,
        Primitive::i64
            | Primitive::u64
            | Primitive::i128
            | Primitive::u128
            | Primitive::isize
            | Primitive::usize
            | Primitive::f16
            | Primitive::f32
            | Primitive::f64
            | Primitive::f128
    );
    (is_numeric && !renders_as_plain_number).then_some(Primitive::i32)
}

/// Recursively coerce wide numerics anywhere in a datatype tree, honouring the
/// number policy: `number` (the default) or `bigint` for 64-bit-and-wider ints.
fn coerce_tree(dt: &mut DataType, numbers: NumberPolicy) {
    if numbers == NumberPolicy::BigInt {
        if let DataType::Primitive(p) = dt {
            if is_wide_integer(p) {
                // `Generic` renders as a bare token, which is the only way to emit
                // `bigint` through specta-typescript (it refuses 64-bit ints
                // outright, since JSON would lose precision — MessagePack doesn't).
                *dt = DataType::Generic(specta::datatype::Generic::new(
                    std::borrow::Cow::Borrowed("bigint"),
                ));
                return;
            }
        }
    }
    coerce_leaf_and_children(dt, numbers);
}

/// Integers that exceed JS `number` precision.
fn is_wide_integer(p: &Primitive) -> bool {
    matches!(
        p,
        Primitive::i64
            | Primitive::u64
            | Primitive::i128
            | Primitive::u128
            | Primitive::isize
            | Primitive::usize
    )
}

/// The `number` policy: coerce every wide numeric to a plain `number`, recursing
/// into containers, struct fields and enum variants.
fn coerce_leaf_and_children(dt: &mut DataType, numbers: NumberPolicy) {
    if let DataType::Primitive(p) = dt {
        if let Some(replacement) = coerced_primitive(p) {
            *dt = DataType::Primitive(replacement);
        }
        return;
    }
    match dt {
        DataType::List(list) => coerce_tree(&mut list.ty, numbers),
        DataType::Map(map) => {
            // A TypeScript index can't be a `bigint`, and the page keys such a
            // map by the key's exact digits (the runtime's `mapKey`): a string.
            let wide_key = numbers == NumberPolicy::BigInt
                && matches!(map.key_ty_mut(), DataType::Primitive(p) if is_wide_integer(p));
            if wide_key {
                *map.key_ty_mut() = DataType::Primitive(Primitive::str);
            } else {
                coerce_tree(map.key_ty_mut(), numbers);
            }
            coerce_tree(map.value_ty_mut(), numbers);
        }
        DataType::Nullable(inner) => coerce_tree(inner, numbers),
        DataType::Tuple(tuple) => tuple
            .elements
            .iter_mut()
            .for_each(|element| coerce_tree(element, numbers)),
        DataType::Intersection(parts) => {
            parts.iter_mut().for_each(|part| coerce_tree(part, numbers))
        }
        DataType::Struct(strct) => coerce_fields(&mut strct.fields, numbers),
        DataType::Enum(enm) => {
            for (_, variant) in enm.variants.iter_mut() {
                coerce_fields(&mut variant.fields, numbers);
            }
        }
        // An inline type (`serde_json::Value`, `#[specta(inline)]`) carries its
        // definition at the use site rather than in the collection, and a
        // generic reference its arguments: both are ours to coerce.
        DataType::Reference(specta::datatype::Reference::Named(named)) => match &mut named.inner {
            NamedReferenceType::Inline { dt, .. } => coerce_tree(dt, numbers),
            NamedReferenceType::Reference { generics, .. } => generics
                .iter_mut()
                .for_each(|(_, dt)| coerce_tree(dt, numbers)),
            _ => {}
        },
        _ => {}
    }
}

fn coerce_fields(fields: &mut specta::datatype::Fields, numbers: NumberPolicy) {
    use specta::datatype::Fields;
    match fields {
        Fields::Unit => {}
        Fields::Unnamed(unnamed) => {
            for field in unnamed.fields.iter_mut() {
                if let Some(ty) = field.ty.as_mut() {
                    coerce_tree(ty, numbers);
                }
            }
        }
        Fields::Named(named) => {
            for (_, field) in named.fields.iter_mut() {
                if let Some(ty) = field.ty.as_mut() {
                    coerce_tree(ty, numbers);
                }
            }
        }
    }
}

/// The TypeScript name `serde_json::Value` renders as. specta-typescript can
/// only inline it, and refuses to, since it's recursive (`Value` holds
/// `Vec<Value>`); so codegen names it and declares [`JSON_VALUE_TS`] itself.
const JSON_VALUE: &str = "JsonValue";
const JSON_VALUE_TS: &str = "/** Any JSON value — `serde_json::Value` on the Rust side. */\n\
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n";
/// With `codegen_bigint()` a number past 2^53 in it decodes as a `bigint`.
const JSON_VALUE_BIGINT_TS: &str = "/** Any JSON value — `serde_json::Value` on the Rust side. */\n\
export type JsonValue = null | boolean | number | bigint | string | JsonValue[] | { [key: string]: JsonValue };\n\n";

/// Replace every `serde_json::Value` in a datatype tree with [`JSON_VALUE`].
fn name_json_values(dt: &mut DataType, types: &Types) {
    use specta::datatype::{Fields, Reference};
    let fields = |fields: &mut Fields, types: &Types| match fields {
        Fields::Unit => {}
        Fields::Unnamed(unnamed) => unnamed
            .fields
            .iter_mut()
            .filter_map(|f| f.ty.as_mut())
            .for_each(|ty| name_json_values(ty, types)),
        Fields::Named(named) => named
            .fields
            .iter_mut()
            .filter_map(|(_, f)| f.ty.as_mut())
            .for_each(|ty| name_json_values(ty, types)),
    };
    match dt {
        DataType::Reference(Reference::Named(named)) => {
            let is_json = types.get(named).is_some_and(|ndt| {
                ndt.name == "Value" && ndt.module_path.starts_with("serde_json")
            });
            if is_json {
                *dt = DataType::Generic(specta::datatype::Generic::new(Cow::Borrowed(JSON_VALUE)));
                return;
            }
            match &mut named.inner {
                NamedReferenceType::Inline { dt, .. } => name_json_values(dt, types),
                NamedReferenceType::Reference { generics, .. } => generics
                    .iter_mut()
                    .for_each(|(_, dt)| name_json_values(dt, types)),
                _ => {}
            }
        }
        DataType::List(list) => name_json_values(&mut list.ty, types),
        DataType::Map(map) => {
            name_json_values(map.key_ty_mut(), types);
            name_json_values(map.value_ty_mut(), types);
        }
        DataType::Nullable(inner) => name_json_values(inner, types),
        DataType::Tuple(tuple) => tuple
            .elements
            .iter_mut()
            .for_each(|element| name_json_values(element, types)),
        DataType::Intersection(parts) => parts
            .iter_mut()
            .for_each(|part| name_json_values(part, types)),
        DataType::Struct(strct) => fields(&mut strct.fields, types),
        DataType::Enum(enm) => enm
            .variants
            .iter_mut()
            .for_each(|(_, variant)| fields(&mut variant.fields, types)),
        _ => {}
    }
}

/// Elyra's export policy: identity, except numerics are coerced so they render
/// as a plain `number`. Applied at the leaf (facade) and across the collection
/// (named-type fields).
struct ElyraFormat {
    numbers: NumberPolicy,
}

impl Format for ElyraFormat {
    fn map_types<'a>(&'a self, types: &Types) -> Result<Cow<'a, Types>, FormatError> {
        // First apply serde's container attributes (rename_all, tagged enums,
        // flatten, skip, ...) via specta-serde, then coerce wide numerics.
        let mut out = specta_serde::Format.map_types(types)?.into_owned();
        let numbers = self.numbers;
        let lookup = out.clone();
        out.iter_mut(|ndt| {
            if let Some(ty) = ndt.ty.as_mut() {
                name_json_values(ty, &lookup);
                coerce_tree(ty, numbers);
            }
        });
        Ok(Cow::Owned(out))
    }

    fn map_type<'a>(
        &'a self,
        types: &Types,
        dt: &DataType,
    ) -> Result<Cow<'a, DataType>, FormatError> {
        let mut out = specta_serde::Format.map_type(types, dt)?.into_owned();
        name_json_values(&mut out, types);
        coerce_tree(&mut out, self.numbers);
        Ok(Cow::Owned(out))
    }
}

/// Render a datatype as a TS type, using the type *name* for named references.
/// A TypeScript string literal for a translation key.
fn ts_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| format!("{s:?}"))
}

/// The typed i18n section of the bindings.
fn typed_translations(translations: &[(String, Vec<String>)]) -> String {
    let mut out = String::new();
    out.push_str(
        "\n/**\n * Every translation key in the fallback locale, with the `:placeholders`\n \
         * its message uses. `$t` / `$tc` below are checked against it: an unknown\n \
         * key, or a missing parameter, is a compile error.\n */\n",
    );
    out.push_str("export type Translations = {\n");
    for (key, params) in translations {
        let fields: Vec<String> = params
            .iter()
            .map(|p| format!("{p}: string | number"))
            .collect();
        let body = if fields.is_empty() {
            "{}".to_owned()
        } else {
            format!("{{ {} }}", fields.join("; "))
        };
        let _ = writeln!(out, "  {}: {body};", ts_string(key));
    }
    out.push_str("};\n\n");
    out.push_str("/** A translation key that exists in the fallback locale. */\n");
    out.push_str("export type TranslationKey = keyof Translations;\n\n");
    out.push_str(
        "type TranslationArgs<P> = {} extends P ? [params?: P] : [params: P];\n\
         type ParamsOf<K extends TranslationKey> = Translations[K];\n\
         /** `:count` is filled in by `tc` itself. */\n\
         type ChoiceParamsOf<K extends TranslationKey> = Omit<Translations[K], \"count\">;\n\
         type RawParams = Record<string, string | number> | undefined;\n\n",
    );
    out.push_str(
        "/** `$t(\"key\", { ..params })`, checked against [`Translations`]. */\n\
         export const t = rawT as unknown as {\n  \
         subscribe(\n    run: (value: <K extends TranslationKey>(key: K, ...params: TranslationArgs<ParamsOf<K>>) => string) => void,\n  \
         ): () => void;\n};\n\n",
    );
    out.push_str(
        "/** `$tc(\"key\", count, { ..params })`, checked against [`Translations`]. */\n\
         export const tc = rawTc as unknown as {\n  \
         subscribe(\n    run: (\n      value: <K extends TranslationKey>(\n        key: K,\n        count: number,\n        ...params: TranslationArgs<ChoiceParamsOf<K>>\n      ) => string,\n    ) => void,\n  \
         ): () => void;\n};\n\n",
    );
    out.push_str(
        "/** `translate(key, params)` outside a component, typed. */\n\
         export function translate<K extends TranslationKey>(key: K, ...params: TranslationArgs<ParamsOf<K>>): string {\n  \
         return rawTranslate(key, params[0] as RawParams);\n}\n\n",
    );
    out.push_str(
        "/** `choice(key, count, params)` outside a component, typed. */\n\
         export function choice<K extends TranslationKey>(\n  key: K,\n  count: number,\n  ...params: TranslationArgs<ChoiceParamsOf<K>>\n): string {\n  \
         return rawChoice(key, count, params[0] as RawParams);\n}\n",
    );
    out
}

/// Where a value's wide integers are (RFC 0045), for the runtime's `wide(..)`.
#[derive(Clone, Debug, PartialEq)]
enum Shape {
    /// A wide integer.
    Wide,
    /// Each item of an array.
    Each(Box<Shape>),
    /// An object's fields (`*`: every value of a map, `0`: a tuple's first).
    Fields(std::collections::BTreeMap<String, Shape>),
}

impl Shape {
    fn fields(fields: impl IntoIterator<Item = (String, Shape)>) -> Option<Shape> {
        let map: std::collections::BTreeMap<String, Shape> = fields.into_iter().collect();
        (!map.is_empty()).then_some(Shape::Fields(map))
    }

    /// Both: an intersection's parts, an enum's variants.
    fn merge(self, other: Shape) -> Shape {
        match (self, other) {
            (Shape::Fields(mut a), Shape::Fields(b)) => {
                for (key, shape) in b {
                    let merged = match a.remove(&key) {
                        Some(existing) => existing.merge(shape),
                        None => shape,
                    };
                    a.insert(key, merged);
                }
                Shape::Fields(a)
            }
            (a, _) => a,
        }
    }

    /// As a JS literal: `1`, `[..]`, `{ "key": .. }`.
    fn js(&self) -> String {
        match self {
            Shape::Wide => "1".into(),
            Shape::Each(inner) => format!("[{}]", inner.js()),
            Shape::Fields(fields) => {
                let parts: Vec<String> = fields
                    .iter()
                    .map(|(key, shape)| {
                        format!(
                            "{}: {}",
                            serde_json::to_string(key).unwrap_or_default(),
                            shape.js()
                        )
                    })
                    .collect();
                format!("{{ {} }}", parts.join(", "))
            }
        }
    }
}

/// The generic parameters in scope: each one's shape at the use site.
type ShapeEnv = Vec<(String, Option<Shape>)>;

/// Where `dt`'s wide integers are, after [`ElyraFormat`] made each one a
/// `bigint` generic; `None` when it has none. `seen` cuts a recursive type
/// off where it comes round again.
fn shape_of(dt: &DataType, types: &Types, env: &ShapeEnv, seen: &mut Vec<String>) -> Option<Shape> {
    use specta::datatype::{Fields, Reference};
    let of_fields = |fields: &Fields, seen: &mut Vec<String>| -> Option<Shape> {
        match fields {
            Fields::Unit => None,
            Fields::Unnamed(unnamed) => {
                let shapes: Vec<(String, Shape)> = unnamed
                    .fields
                    .iter()
                    .enumerate()
                    .filter_map(|(i, f)| {
                        f.ty.as_ref()
                            .and_then(|ty| shape_of(ty, types, env, seen))
                            .map(|s| (i.to_string(), s))
                    })
                    .collect();
                // A newtype is its one field, as serde sends it.
                if unnamed.fields.len() == 1 {
                    return shapes.into_iter().next().map(|(_, s)| s);
                }
                Shape::fields(shapes)
            }
            Fields::Named(named) => Shape::fields(named.fields.iter().filter_map(|(name, f)| {
                f.ty.as_ref()
                    .and_then(|ty| shape_of(ty, types, env, seen))
                    .map(|s| (name.to_string(), s))
            })),
        }
    };
    match dt {
        DataType::Generic(g) => match env.iter().find(|(name, _)| name == g.name().as_ref()) {
            Some((_, shape)) => shape.clone(),
            None => (g.name() == "bigint").then_some(Shape::Wide),
        },
        DataType::List(list) => {
            shape_of(&list.ty, types, env, seen).map(|s| Shape::Each(Box::new(s)))
        }
        DataType::Map(map) => shape_of(map.value_ty(), types, env, seen)
            .and_then(|s| Shape::fields([("*".to_string(), s)])),
        DataType::Nullable(inner) => shape_of(inner, types, env, seen),
        DataType::Tuple(tuple) => Shape::fields(
            tuple
                .elements
                .iter()
                .enumerate()
                .filter_map(|(i, e)| shape_of(e, types, env, seen).map(|s| (i.to_string(), s))),
        ),
        DataType::Intersection(parts) => parts
            .iter()
            .filter_map(|p| shape_of(p, types, env, seen))
            .reduce(Shape::merge),
        DataType::Struct(strct) => of_fields(&strct.fields, seen),
        // A variant's fields where serde may put them: under its name
        // (externally tagged) and beside the tag (internally, or untagged).
        DataType::Enum(enm) => enm
            .variants
            .iter()
            .filter(|(_, v)| !v.skip)
            .filter_map(|(name, v)| {
                of_fields(&v.fields, seen).map(|s| {
                    let tagged = Shape::Fields([(name.to_string(), s.clone())].into());
                    match s {
                        Shape::Fields(_) => tagged.merge(s),
                        _ => tagged,
                    }
                })
            })
            .reduce(Shape::merge),
        DataType::Reference(Reference::Named(named)) => match &named.inner {
            NamedReferenceType::Inline { dt, .. } => shape_of(dt, types, env, seen),
            NamedReferenceType::Reference { generics, .. } => {
                let ndt = types.get(named)?;
                let key = ndt.name.to_string();
                if seen.contains(&key) {
                    return None;
                }
                let inner_env: ShapeEnv = generics
                    .iter()
                    .map(|(g, arg)| (g.name().to_string(), shape_of(arg, types, env, seen)))
                    .collect();
                seen.push(key);
                let shape = ndt
                    .ty
                    .as_ref()
                    .and_then(|ty| shape_of(ty, types, &inner_env, seen));
                seen.pop();
                shape
            }
            _ => None,
        },
        _ => None,
    }
}

fn render_ty(fw: &FrameworkExporter, dt: &DataType) -> Result<String, TsError> {
    match dt {
        DataType::Reference(r) => fw.reference(r),
        // `Option<Named>`: the name, or null — not the type spelled out.
        DataType::Nullable(inner) => match inner.as_ref() {
            DataType::Reference(r) => Ok(format!("{} | null", fw.reference(r)?)),
            other => fw.inline(&DataType::Nullable(Box::new(other.clone()))),
        },
        other => fw.inline(other),
    }
}

/// A registered channel name plus a function that resolves its payload type.
pub type EventTypeDef = (&'static str, fn(&mut Types) -> DataType);

/// One registered event channel and its payload type.
pub struct EventSig {
    pub channel: String,
    pub payload: DataType,
}

/// How integers wider than 2^53 are exported.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum NumberPolicy {
    /// Every numeric renders as `number` (MessagePack round-trips i64, but values
    /// beyond 2^53 lose precision once JS parses them).
    #[default]
    Number,
    /// 64-bit and wider integers render as `bigint`.
    BigInt,
}

/// What a command's JSDoc says (RFC 0025): from the registry, not from
/// [`CommandSig`], which a hand-written `Command` builds.
#[derive(Clone, Copy)]
struct CommandDoc {
    description: &'static str,
    ability: Option<&'static str>,
    live: bool,
    has_args: bool,
}

/// Where a JSDoc block goes: above `api.*`, which says it's live too, or
/// above `live.*`, which is the live store itself.
#[derive(Clone, Copy, PartialEq)]
enum DocFor {
    Api,
    Live,
}

/// The JSDoc block above a command's entry, indented for an object member;
/// empty when there's nothing to say, so an undocumented app's bindings
/// don't change.
fn jsdoc(name: &str, doc: &CommandDoc, for_: DocFor) -> String {
    let mut remarks = Vec::new();
    if let Some(ability) = doc.ability {
        remarks.push(format!("Needs `{ability}`."));
    }
    if doc.live && for_ == DocFor::Api {
        let args = if doc.has_args { ".." } else { "" };
        remarks.push(format!(
            "Live: `live.{name}({args})` re-runs it when the data it read changes."
        ));
    }
    let description = doc.description.trim();
    if description.is_empty() && remarks.is_empty() {
        return String::new();
    }
    // A `*/` in the doc comment would end the block early.
    let escape = |line: &str| line.replace("*/", "*\\/");
    let mut out = String::from("  /**\n");
    for line in description.lines() {
        let line = escape(line.trim_end());
        if line.is_empty() {
            out.push_str("   *\n");
        } else {
            let _ = writeln!(out, "   * {line}");
        }
    }
    if !remarks.is_empty() {
        if !description.is_empty() {
            out.push_str("   *\n");
        }
        let _ = writeln!(out, "   * @remarks {}", escape(&remarks.join(" ")));
    }
    out.push_str("   */\n");
    out
}

/// Generate the full `bindings.ts` contents for a registry.
pub fn generate(registry: &CommandRegistry) -> Result<String, String> {
    generate_with(registry, &[], NumberPolicy::Number)
}

/// Generate bindings including typed event channels and an explicit number policy.
pub fn generate_with(
    registry: &CommandRegistry,
    events: &[EventTypeDef],
    numbers: NumberPolicy,
) -> Result<String, String> {
    generate_all(registry, events, numbers, &[])
}

/// [`generate_with`], plus typed `t` / `tc` for a translation catalog: each key
/// with the placeholder names its message needs (from
/// `Translator::codegen_keys`).
pub fn generate_all(
    registry: &CommandRegistry,
    events: &[EventTypeDef],
    numbers: NumberPolicy,
    translations: &[(String, Vec<String>)],
) -> Result<String, String> {
    let translations = translations.to_vec();
    let mut types = Types::default();

    let mut sigs: Vec<CommandSig> = registry
        .commands()
        .map(|cmd| cmd.signature(&mut types))
        .collect();
    sigs.sort_by_key(|sig| sig.name);
    // `#[command(live)]`s also get a `live.*` entry (RFC 0002).
    let live: std::collections::BTreeSet<&'static str> = registry
        .commands()
        .filter(|cmd| cmd.live())
        .map(|cmd| cmd.name())
        .collect();
    // What each command's JSDoc says (RFC 0025).
    let docs: std::collections::BTreeMap<&'static str, CommandDoc> = registry
        .commands()
        .map(|cmd| {
            let doc = CommandDoc {
                description: cmd.description(),
                ability: cmd.ability(),
                live: cmd.live(),
                has_args: false,
            };
            (cmd.name(), doc)
        })
        .collect();

    let mut event_sigs: Vec<EventSig> = events
        .iter()
        .map(|(channel, definition)| EventSig {
            channel: (*channel).to_string(),
            payload: definition(&mut types),
        })
        .collect();
    event_sigs.sort_by(|a, b| a.channel.cmp(&b.channel));

    // With `codegen_bigint()`, where each result's wide integers are (RFC
    // 0045), from the types as they're exported: each wide integer is then a
    // `bigint` generic.
    let bigint = numbers == NumberPolicy::BigInt;
    let mut ret_shapes: std::collections::BTreeMap<&'static str, String> = Default::default();
    let mut event_shapes: Vec<(String, String)> = Vec::new();
    if bigint {
        let format = ElyraFormat { numbers };
        let formatted = format
            .map_types(&types)
            .map_err(|e| e.to_string())?
            .into_owned();
        for sig in &sigs {
            let mapped = format
                .map_type(&types, &sig.ret)
                .map_err(|e| e.to_string())?;
            if let Some(shape) = shape_of(&mapped, &formatted, &Vec::new(), &mut Vec::new()) {
                ret_shapes.insert(sig.name, shape.js());
            }
        }
        for event in &event_sigs {
            let mapped = format
                .map_type(&types, &event.payload)
                .map_err(|e| e.to_string())?;
            if let Some(shape) = shape_of(&mapped, &formatted, &Vec::new(), &mut Vec::new()) {
                event_shapes.push((event.channel.clone(), shape.js()));
            }
        }
    }

    // specta-typescript refuses to emit `bigint` unless told to; the number policy
    // decides whether wide integers stay `number` or become `bigint`.
    // `framework_runtime` lives on `Exporter`; `Typescript` is a thin wrapper.
    Exporter::from(Typescript::default())
        .header(HEADER)
        .framework_prelude("") // drop the default "generated by Specta" line
        .framework_runtime(move |mut fw| {
            let mut out = String::new();
            let mut imports = vec!["invoke"];
            if !live.is_empty() {
                // `rawLive` for the live commands without a wide integer.
                if live.iter().any(|name| !ret_shapes.contains_key(name)) {
                    imports.push("live as rawLive");
                }
                imports.push("type LiveStore");
            }
            if !event_sigs.is_empty() {
                imports.push("channel as rawChannel");
            }
            if bigint {
                imports.push("bigintPolicy");
                if !ret_shapes.is_empty() || !event_shapes.is_empty() {
                    imports.push("wide");
                }
                if live.iter().any(|name| ret_shapes.contains_key(name)) {
                    imports.push("liveWith as rawLiveWith");
                }
                if !event_shapes.is_empty() {
                    imports.push("type WideShape");
                }
            }
            if !translations.is_empty() {
                imports.extend([
                    "t as rawT",
                    "tc as rawTc",
                    "translate as rawTranslate",
                    "choice as rawChoice",
                ]);
            }
            let _ = writeln!(
                out,
                "import {{ {} }} from \"@elyra/runtime\";\n",
                imports.join(", ")
            );
            if bigint {
                // The runtime warns when the app and these bindings disagree.
                out.push_str("bigintPolicy(true);\n\n");
            }

            // 1. User types (interfaces/enums). Marks them as manually exported.
            let rendered = fw.render_types()?;
            if !rendered.trim().is_empty() {
                out.push_str(rendered.trim());
                out.push_str("\n\n");
            }

            // 2. The typed api.* facade.
            out.push_str("export const api = {\n");
            for sig in &sigs {
                if let Some(doc) = docs.get(sig.name) {
                    let doc = CommandDoc { has_args: !sig.args.is_empty(), ..*doc };
                    out.push_str(&jsdoc(sig.name, &doc, DocFor::Api));
                }
                let mut params = String::new();
                let mut call_args = String::new();
                for (i, (name, dt)) in sig.args.iter().enumerate() {
                    if i > 0 {
                        params.push_str(", ");
                        call_args.push_str(", ");
                    }
                    let ty = render_ty(&fw, dt)?;
                    let _ = write!(params, "{name}: {ty}");
                    call_args.push_str(name);
                }
                let ret = render_ty(&fw, &sig.ret)?;
                let sep = if sig.args.is_empty() { "" } else { ", " };
                match ret_shapes.get(sig.name) {
                    Some(shape) => {
                        let _ = write!(
                            out,
                            "  {name}({params}): Promise<{ret}> {{\n    return invoke(\"{name}\"{sep}{call_args}).then(wide<{ret}>({shape}));\n  }},\n",
                            name = sig.name,
                        );
                    }
                    None => {
                        let _ = write!(
                            out,
                            "  {name}({params}): Promise<{ret}> {{\n    return invoke(\"{name}\"{sep}{call_args});\n  }},\n",
                            name = sig.name,
                        );
                    }
                }
            }
            out.push_str("};\n");

            // 2b. Live queries: a store per `#[command(live)]`, re-run in Rust
            //     whenever the data it read changes.
            if !live.is_empty() {
                out.push_str(
                    "\n/** Live queries: a store per `#[command(live)]`, updated whenever the data it read changes. */\n",
                );
                out.push_str("export const live = {\n");
                for sig in sigs.iter().filter(|sig| live.contains(sig.name)) {
                    if let Some(doc) = docs.get(sig.name) {
                        out.push_str(&jsdoc(sig.name, doc, DocFor::Live));
                    }
                    let mut params = String::new();
                    let mut call_args = String::new();
                    for (i, (name, dt)) in sig.args.iter().enumerate() {
                        if i > 0 {
                            params.push_str(", ");
                        }
                        let ty = render_ty(&fw, dt)?;
                        let _ = write!(params, "{name}: {ty}");
                        let _ = write!(call_args, ", {name}");
                    }
                    let ret = render_ty(&fw, &sig.ret)?;
                    match ret_shapes.get(sig.name) {
                        Some(shape) => {
                            let _ = write!(
                                out,
                                "  {name}({params}): LiveStore<{ret}> {{\n    return rawLiveWith<{ret}>(wide<{ret}>({shape}), \"{name}\"{call_args});\n  }},\n",
                                name = sig.name,
                            );
                        }
                        None => {
                            let _ = write!(
                                out,
                                "  {name}({params}): LiveStore<{ret}> {{\n    return rawLive<{ret}>(\"{name}\"{call_args});\n  }},\n",
                                name = sig.name,
                            );
                        }
                    }
                }
                out.push_str("};\n");
            }

            // 3. Typed event channels: a name -> payload map plus a narrowed
            //    `channel()` so both sides are checked at compile time.
            if !event_sigs.is_empty() {
                out.push_str("\n/** Every event channel the Rust side emits, with its payload. */\n");
                out.push_str("export type ElyraEvents = {\n");
                for event in &event_sigs {
                    let ty = render_ty(&fw, &event.payload)?;
                    let _ = writeln!(out, "  \"{}\": {ty};", event.channel);
                }
                out.push_str("};\n\n");
                out.push_str("/** A channel name known to the Rust side. */\n");
                out.push_str("export type ElyraEventName = keyof ElyraEvents;\n\n");
                if !event_shapes.is_empty() {
                    // Where each payload's wide integers are (RFC 0045).
                    out.push_str("const eventShapes: { [channel: string]: WideShape } = {\n");
                    for (channel, shape) in &event_shapes {
                        let _ = writeln!(out, "  \"{channel}\": {shape},");
                    }
                    out.push_str("};\n\n");
                }
                out.push_str(
                    "/**\n * Subscribe to a typed event channel. Unlike the untyped\n                     * `channel()` from `@elyra/runtime`, both the name and the payload\n                     * are checked against the Rust definitions.\n */\n",
                );
                if event_shapes.is_empty() {
                    out.push_str(
                        "export function channel<K extends ElyraEventName>(\n  name: K,\n): {\n  subscribe: (handler: (value: ElyraEvents[K] | undefined) => void) => () => void;\n} {\n  return rawChannel<ElyraEvents[K]>(name);\n}\n",
                    );
                } else {
                    out.push_str(
                        "export function channel<K extends ElyraEventName>(\n  name: K,\n): {\n  subscribe: (handler: (value: ElyraEvents[K] | undefined) => void) => () => void;\n} {\n  const raw = rawChannel<ElyraEvents[K]>(name);\n  const shape = eventShapes[name];\n  if (!shape) return raw;\n  const widen = wide<ElyraEvents[K]>(shape);\n  return {\n    subscribe: (handler) => raw.subscribe((value) => handler(value === undefined ? value : widen(value))),\n  };\n}\n",
                    );
                }
            }

            // 4. Typed translations: every key in the fallback catalog with the
            //    parameters its message needs, and `t` / `tc` narrowed to them.
            if !translations.is_empty() {
                out.push_str(&typed_translations(&translations));
            }

            // 5. `JsonValue`, when a `serde_json::Value` was named as one.
            if out.contains(JSON_VALUE) {
                let after_imports = out.find("\n\n").map_or(0, |i| i + 2);
                out.insert_str(
                    after_imports,
                    if bigint { JSON_VALUE_BIGINT_TS } else { JSON_VALUE_TS },
                );
            }

            Ok(Cow::Owned(out))
        })
        .export(&types, ElyraFormat { numbers })
        .map_err(|err| err.to_string())
}
