/// What Laravel needs, printed: the table, the routes the app reads and
/// marks through, the event that tells the desktop "read on the web", and
/// a notification that's sent to both.
pub(crate) fn laravel_side() -> &'static str {
    r#"On the Laravel side (RFC 0008):

  php artisan make:notifications-table && php artisan migrate

  // app/Http/Controllers/NotificationController.php
  class NotificationController extends Controller
  {
      public function index(Request $request)
      {
          $user = $request->user();
          return $user->notifications()->paginate(20)->toArray()
              + ['unread' => $user->unreadNotifications()->count()];
      }

      public function read(Request $request, string $id)
      {
          $request->user()->notifications()->whereKey($id)->firstOrFail()->markAsRead();
          broadcast(new NotificationsRead($request->user(), [$id]))->toOthers();
          return response()->noContent();
      }

      public function readAll(Request $request)
      {
          $request->user()->unreadNotifications->markAsRead();
          broadcast(new NotificationsRead($request->user()))->toOthers();
          return response()->noContent();
      }
  }

  // routes/api.php, under auth:sanctum
  Route::get('/notifications', [NotificationController::class, 'index']);
  Route::post('/notifications/read-all', [NotificationController::class, 'readAll']);
  Route::post('/notifications/{id}/read', [NotificationController::class, 'read']);

  // app/Events/NotificationsRead.php — "read on the web", heard on the desktop
  class NotificationsRead implements ShouldBroadcastNow
  {
      public function __construct(public User $user, public ?array $ids = null) {}

      public function broadcastOn(): array
      {
          return [new PrivateChannel('App.Models.User.'.$this->user->id)];
      }

      public function broadcastAs(): string
      {
          return 'NotificationsRead';
      }

      public function broadcastWith(): array
      {
          return ['ids' => $this->ids];
      }
  }

  // A notification for the desktop: kept for the list, and broadcast
  class InvoicePaid extends Notification
  {
      public function via(object $notifiable): array
      {
          return ['database', 'broadcast'];
      }

      public function toArray(object $notifiable): array
      {
          return ['title' => 'Invoice paid', 'body' => "…", 'url' => "/invoices/{$this->invoice->id}"];
      }
  }

  // routes/channels.php — Laravel's default, kept
  Broadcast::channel('App.Models.User.{id}', fn ($user, $id) => (int) $user->id === (int) $id);"#
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn it_needs_the_backend_feature() {
        assert!(has_backend(
            "[dependencies]\nelyra = { path = \"x\", features = [\"database\", \"backend\"] }\n"
        ));
        assert!(!has_backend(
            "[dependencies]\nelyra = { path = \"x\", features = [\"database\"] }\n"
        ));
        assert!(!has_backend(
            "[dependencies]\nother = { features = [\"backend\"] }\n"
        ));
    }

    #[test]
    fn the_files_follow_the_list_and_count_it() {
        let files = files();
        let index = &files.iter().find(|(f, _)| f == "index.js").unwrap().1;
        assert!(index.contains("\"/notifications\": () => import(\"./Index.svelte\")"));
        assert!(index.contains("count: unread"));
        assert!(
            index.contains("notifications.subscribe(() => {})"),
            "followed app-wide"
        );
        assert!(index.contains("e.shown !== \"toast\""));
        let page = &files.iter().find(|(f, _)| f == "Index.svelte").unwrap().1;
        assert!(page.contains("notifications.markRead(n.id)"));
        assert!(page.contains("notifications.markAllRead()"));
        assert!(page.contains("!url.startsWith(\"//\")"), "never a full URL");
    }

    #[test]
    fn laravels_side_has_the_routes_the_app_calls() {
        let side = laravel_side();
        for needed in [
            "make:notifications-table",
            "['unread' => $user->unreadNotifications()->count()]",
            "Route::get('/notifications'",
            "Route::post('/notifications/read-all'",
            "Route::post('/notifications/{id}/read'",
            "return 'NotificationsRead';",
            "PrivateChannel('App.Models.User.'",
            "['database', 'broadcast']",
        ] {
            assert!(side.contains(needed), "missing: {needed}");
        }
    }

    #[test]
    fn arguments() {
        assert!(parse_args(&["--force".into(), "--dry-run".into()]).is_ok());
        assert!(parse_args(&["--view".into()]).is_err());
    }
}
