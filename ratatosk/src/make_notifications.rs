//! `rata make:notifications` (RFC 0008): the app's side of Laravel's
//! notifications — a page listing them, a place in the navigation with the
//! unread count, toasts while the app is in front — and Laravel's side,
//! printed. The files are the app's to change; rata lists the folder in the
//! resource registry, and never edits `main.rs` or `App.svelte`.

use std::path::Path;

use crate::config::Config;
use crate::resource::{self, Layout};

pub fn make_notifications(cfg: &Config) -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(2).collect();
    run(cfg, &args)
}

struct Options {
    force: bool,
    dry_run: bool,
}

fn parse_args(args: &[String]) -> Result<Options, String> {
    let mut opts = Options {
        force: false,
        dry_run: false,
    };
    for arg in args {
        match arg.as_str() {
            "--force" => opts.force = true,
            "--dry-run" => opts.dry_run = true,
            other => return Err(format!("unknown argument `{other}`")),
        }
    }
    Ok(opts)
}

/// Whether `Cargo.toml`'s `elyra` dependency has the `backend` feature.
fn has_backend(manifest: &str) -> bool {
    manifest
        .lines()
        .any(|line| line.trim_start().starts_with("elyra") && line.contains("\"backend\""))
}

fn run(cfg: &Config, args: &[String]) -> Result<(), String> {
    let opts = parse_args(args)?;
    let manifest = std::fs::read_to_string(cfg.root.join("Cargo.toml"))
        .map_err(|e| format!("Cargo.toml: {e}"))?;
    if !has_backend(&manifest) {
        return Err(
            "the notifications are Laravel's: Cargo.toml needs `elyra` with \
             `features = [\"backend\", …]` (rata doesn't edit it)"
                .into(),
        );
    }
    let layout = Layout::new(&cfg.root, Path::new(&cfg.frontend_dir));
    let dir = layout.js.join("notifications");
    if dir.exists() && !opts.force {
        return Err(format!(
            "{} already exists — pass --force to regenerate it",
            dir.display()
        ));
    }
    let files = files();
    if opts.dry_run {
        println!("Would write:");
        for (file, _) in &files {
            println!("  {}", dir.join(file).display());
        }
        println!("  and the registry");
        return Ok(());
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for (file, contents) in &files {
        let path = dir.join(file);
        std::fs::write(&path, contents).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("Wrote {}", path.display());
    }
    for path in resource::sync(&layout)? {
        println!("Updated {}", path.display());
    }

    println!("\nPage: #/notifications, in the navigation with the unread count.");
    println!("\n{}", laravel_side());
    for hint in hints(cfg, &layout) {
        println!("\n{hint}");
    }
    Ok(())
}

/// What the app still needs — read-only, like every rata hint.
fn hints(cfg: &Config, layout: &Layout) -> Vec<String> {
    let mut hints = Vec::new();
    let main = std::fs::read_to_string(&layout.main_rs).unwrap_or_default();
    if !main.contains(".notifications()") {
        hints.push(format!(
            "In {}, on your `Backend` (Laravel's notifications arrive through its\n  \
             broadcasting, RFC 0006):\n  \
             .broadcasting(elyra::Broadcasting::pusher(key))   // REVERB_APP_KEY; Askr's --pusher too\n  \
             .notifications()",
            layout.main_rs.display()
        ));
    }
    let app = cfg
        .root
        .join(&cfg.frontend_dir)
        .join("src")
        .join("App.svelte");
    let shell = std::fs::read_to_string(&app).unwrap_or_default();
    if shell.contains("{#each nav as item") && !shell.contains("item.count") {
        hints.push(format!(
            "For the unread count beside \"Notifications\" in {} (`rata new` does it since\n  \
             0.15), render a nav item's `count` — a store of a number:\n  \
             {{item.label}}{{#if item.count}}<NavCount count={{item.count}} />{{/if}}\n  \
             with NavCount.svelte from a new project.",
            app.display()
        ));
    }
    hints
}

fn files() -> Vec<(String, String)> {
    vec![
        ("index.js".into(), INDEX_JS.into()),
        ("Index.svelte".into(), INDEX_SVELTE.into()),
    ]
}

const INDEX_JS: &str = r#"// Laravel's notifications (RFC 0008) — generated by `rata make:notifications`,
// and yours to change. rata lists this folder in ../index.js.
import { notifications, onNotification, toast } from "@elyra/runtime";

export const routes = {
  "/notifications": () => import("./Index.svelte"),
};

/** The unread count, as a store of a number, for the navigation. */
const unread = {
  subscribe: (run) => notifications.subscribe((state) => run(state.unread)),
};

export const nav = [{ label: "Notifications", path: "/notifications", count: unread }];

// For as long as the app runs: the list is followed, so a click on a
// notification in the OS opens its page in the app.
notifications.subscribe(() => {});

// While the app is in front, the OS shows nothing: a toast does.
onNotification((e) => {
  if (e.shown !== "toast") return;
  const { title, body } = e.presented;
  toast(body ? `${title} — ${body}` : title);
});
"#;

