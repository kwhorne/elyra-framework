// Writes a Svelte component for every WireCharts chart (RFC 0059) from the
// fixtures `wirecharts-fixtures.php` made: its props and their defaults, the
// ECharts parts it draws with, and its docs blurb. The six of 0.58 (Line,
// Area, Column, Bar, Pie, Scatter) are written by hand and left alone.
//
//   node scripts/components.mjs           # write them
//   node scripts/components.mjs --check   # fail if any is out of date

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { NOT_PROPS, exampleOf, nameOf } from "../docs/examples.js";

const here = new URL("../", import.meta.url).pathname;
// Which family module holds each chart's call.
const FAMILIES = ["line", "area", "mixed", "columns", "more"];
const familyOf = {};
for (const family of FAMILIES) {
  const { CALLS } = await import(`${here}src/internal/wirecharts/${family}.js`);
  for (const slug of Object.keys(CALLS)) familyOf[slug] = family;
}
const callOf = (slug) => "call" + slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const fixtures = JSON.parse(readFileSync(`${here}src/test/wirecharts/fixtures.json`, "utf8"));
const HAND = new Set(["line", "area", "column", "bar", "pie", "scatter"]);

const CHARTS = {
  line: "LineChart", bar: "BarChart", pie: "PieChart", scatter: "ScatterChart", effectScatter: "EffectScatterChart",
  radar: "RadarChart", funnel: "FunnelChart", gauge: "GaugeChart", heatmap: "HeatmapChart",
  candlestick: "CandlestickChart", boxplot: "BoxplotChart", tree: "TreeChart", treemap: "TreemapChart",
  sunburst: "SunburstChart", sankey: "SankeyChart", graph: "GraphChart", themeRiver: "ThemeRiverChart",
  pictorialBar: "PictorialBarChart", custom: "CustomChart",
};
const COMPONENTS = {
  markLine: "MarkLineComponent", markArea: "MarkAreaComponent", markPoint: "MarkPointComponent",
  dataZoom: "DataZoomComponent", visualMap: "VisualMapComponent", title: "TitleComponent",
  graphic: "GraphicComponent", polar: "PolarComponent", singleAxis: "SingleAxisComponent",
  radar: "RadarComponent", calendar: "CalendarComponent", dataset: "DatasetComponent",
};
const GL = { bar3D: "Bar3DChart", scatter3D: "Scatter3DChart", surface: "SurfaceChart" };


function partsOf(fixture) {
  const charts = new Set(fixture.parts.charts);
  // `cartesian` picks the series type from a variable.
  if (fixture.builder === "cartesian") charts.add(fixture.component === "column" ? "bar" : "line");
  const gl = [...charts].filter((c) => GL[c]);
  return {
    charts: [...charts].filter((c) => CHARTS[c]).map((c) => CHARTS[c]),
    components: fixture.parts.components.filter((c) => COMPONENTS[c]).map((c) => COMPONENTS[c]),
    gl: gl.map((c) => GL[c]),
    gl3d: fixture.parts.components.includes("grid3D"),
  };
}

const literal = (value) => (value === null ? "null" : JSON.stringify(value));

function source(fixture) {
  const name = nameOf(fixture.component);
  const parts = partsOf(fixture);
  const props = Object.entries(fixture.defaults).filter(([key]) => !NOT_PROPS.has(key));
  const names = props.map(([key]) => key);
  const hasLabels = names.includes("labels");
  const height = typeof fixture.defaults.height === "number" ? fixture.defaults.height : 320;
  // echarts-gl draws on a canvas, with WebGL.
  const gl = parts.gl.length > 0 || parts.gl3d;
  const imports = [];
  if (parts.charts.length) imports.push(`  import { ${parts.charts.join(", ")} } from "echarts/charts";`);
  if (parts.components.length) imports.push(`  import { ${parts.components.join(", ")} } from "echarts/components";`);
  if (parts.gl.length) imports.push(`  import { ${parts.gl.join(", ")} } from "echarts-gl/charts";`);
  if (parts.gl.length || parts.gl3d) imports.push(`  import { Grid3DComponent } from "echarts-gl/components";`);
  const use = [...parts.charts, ...parts.components, ...parts.gl, ...(parts.gl.length || parts.gl3d ? ["Grid3DComponent"] : [])];
  const declared = props
    .map(([key, value]) => (key === "labels" ? `    labels = ${literal(value)},` : `    ${key} = ${literal(value)},`))
    .join("\n");
  const passed = names.map((key) => (key === "labels" ? "labels: names" : key)).join(", ");
  const blurb = fixture.blurb.replace(/--/g, "–");
  return `<!--
  ${blurb}
  WireCharts' \`${fixture.component}\` (RFC 0059): its props, its option, the app's look.
  Generated by scripts/components.mjs from WireCharts' docs; edit the script, not this file.
-->
<script>
${imports.join("\n")}
  import { ${callOf(fixture.component)} } from "./internal/wirecharts/${familyOf[fixture.component]}.js";
  import WireChart from "./internal/WireChart.svelte";

  let {
${declared}
    live = undefined,
    height = ${height},
    label = undefined,
    format = undefined,
    locale = undefined,
    renderer = "${gl ? "canvas" : "svg"}",
    onselect = undefined,${hasLabels ? "" : "\n    labels = {},"}
    class: className = "",
  } = $props();
${
  hasLabels
    ? `
  // A list is WireCharts' names for the points; an object, the chart's words.
  const names = $derived(Array.isArray(labels) ? labels : ${literal(fixture.defaults.labels)});
  const words = $derived(Array.isArray(labels) ? {} : labels);
`
    : ""
}</script>

<WireChart
  slug="${fixture.component}"
  call={${callOf(fixture.component)}}${gl ? "\n  gl" : ""}
  use={[${use.join(", ")}]}
  props={{ ${passed} }}
  {live}
  {height}
  {label}
  {format}
  {locale}
  {renderer}
  {onselect}
  words={${hasLabels ? "words" : "labels"}}
  class={className}
/>
`;
}

const check = process.argv.includes("--check");
const stale = [];
const written = [];
for (const fixture of fixtures) {
  if (HAND.has(fixture.component)) continue;
  const file = `${here}src/${nameOf(fixture.component)}.svelte`;
  const text = source(fixture);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) stale.push(file);
  } else {
    writeFileSync(file, text);
    written.push(nameOf(fixture.component));
  }
}
// The exports: the 3D charts from @elyra/charts/gl (echarts-gl), the rest from @elyra/charts.
const isGl = (f) => partsOf(f).gl.length > 0 || partsOf(f).gl3d;
const generated = fixtures.filter((f) => !HAND.has(f.component));
const exportsOf = (list, head) =>
  `${head}\n${list.map((f) => `export { default as ${nameOf(f.component)} } from "./${nameOf(f.component)}.svelte";`).join("\n")}\n`;
const lists = {
  [`${here}src/wirecharts.js`]: exportsOf(
    generated.filter((f) => !isGl(f)),
    "// WireCharts' charts (RFC 0059), each a component of its own.\n// Generated by scripts/components.mjs; edit the script, not this file.",
  ),
  [`${here}src/gl.js`]: exportsOf(
    generated.filter(isGl),
    "// @elyra/charts/gl (RFC 0059): WireCharts' 3D charts, on echarts-gl and WebGL.\n// Generated by scripts/components.mjs; edit the script, not this file.",
  ),
};
for (const [file, text] of Object.entries(lists)) {
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) stale.push(file);
  } else {
    writeFileSync(file, text);
  }
}

// The reference: every chart, by WireCharts' families, with its example and props.
const SHARED = new Set(["height", "theme", "model", "class", "label"]);
const cell = (text) => String(text).replaceAll("|", "\\|");
const pageOf = () => {
  const families = [...new Set(fixtures.map((f) => f.family))];
  let md = `# Every chart

<!-- Generated by charts/scripts/components.mjs from WireCharts' docs; edit the script, not this file. -->

All of [WireCharts](https://wirecharts.io)' charts, as \`@elyra/charts\`
components ([RFC 0059](proposals/0059-all-of-wirecharts.md)), each with
WireCharts' props and the example from its docs. Every one also takes what
[every chart takes](charts.md#the-charts): \`live\`, \`height\`, \`label\`,
\`format\`, \`locale\`, \`renderer\`, \`onselect\`, \`labels\` and \`class\`. Where a
chart's own \`labels\` names its points, a list is those names and an object
its words.

The 3D charts come from \`@elyra/charts/gl\` and need \`echarts-gl\`
installed beside it.
`;
  for (const family of families) {
    md += `\n## ${family}\n`;
    for (const f of fixtures.filter((x) => x.family === family)) {
      const name = nameOf(f.component);
      const from = isGl(f) ? "@elyra/charts/gl" : "@elyra/charts";
      md += `\n### ${name}\n\n${f.blurb}${HAND.has(f.component) ? " (The 0.58 chart: see [the charts](charts.md#the-charts).)" : ""}\n\n`;
      md += "```svelte\n<script>\n  import { " + name + ' } from "' + from + '";\n</script>\n\n' + exampleOf(f) + "\n```\n";
      const props = f.docProps.filter(([p]) => !SHARED.has(p));
      if (props.length) {
        md += "\n| Prop | Type | Default | |\n|---|---|---|---|\n";
        md += props.map(([p, type, def, what]) => `| \`${p}\` | \`${cell(type)}\` | \`${cell(def)}\` | ${cell(what)} |`).join("\n") + "\n";
      }
    }
  }
  return md;
};
const page = `${here}../docs/charts-reference.md`;
if (check) {
  if (!existsSync(page) || readFileSync(page, "utf8") !== pageOf()) stale.push(page);
} else {
  writeFileSync(page, pageOf());
}

if (check && stale.length) {
  console.error(`out of date (run node scripts/components.mjs):\n${stale.join("\n")}`);
  process.exit(1);
}
if (!check) console.log(`${written.length} components`);
